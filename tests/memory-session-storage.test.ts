test("session directory and projection symlinks or non-file replacements fail before cleanup", async () => {
  for (const shape of ["directory-link", "directory-file", "file-link", "file-directory", "legacy-link", "empty-directory"] as const) {
    const f = await fixture();
    try {
      if (!new Set(["directory-link", "directory-file"]).has(shape)) f.createSession();
      const directory = join(f.store.sessionStorageRoot(f.id), "memory"), legacy = join(sessionBase, legacyId(f.id));
      const external = join(f.root, "external"); mkdirSync(external);
      const sentinel = join(external, "sentinel"); writeFileSync(sentinel, "must survive");
      mkdirSync(sessionBase, { recursive: true });
      mkdirSync(f.store.sessionStorageRoot(f.id), { recursive: true });
      if (shape === "directory-link") symlinkSync(external, directory);
      if (shape === "directory-file") writeFileSync(directory, "not a directory");
      if (shape === "legacy-link") symlinkSync(external, legacy);
      if (shape === "file-link" || shape === "file-directory" || shape === "empty-directory") {
        if (!existsSync(directory)) mkdirSync(directory);
        if (shape === "file-link") symlinkSync(sentinel, join(directory, "memory.md"));
        if (shape === "file-directory") mkdirSync(join(directory, "memory.md"));
      }
      if (shape === "empty-directory") {
        assert.equal(f.files.sync({ kind: "session", id: f.id }).status, "written");
        assert.equal(f.files.archiveSession(f.id).content_deleted, true);
      } else {
        assert.throws(() => f.files.sync({ kind: "session", id: f.id }), /regular/);
        assert.throws(() => f.files.archiveSession(f.id), /regular/);
        const memory = f.store.find("memory_ledger", `memory-${f.id}`);
        const shouldExist = !new Set(["directory-link", "directory-file"]).has(shape);
        assert.equal(memory?.status ?? null, shouldExist ? "active" : null);
      }
      assert.equal(readFileSync(sentinel, "utf8"), "must survive");
    } finally { f.cleanup(); }
  }
});


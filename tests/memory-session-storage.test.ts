test("archive removes both owned session locations and candidates without requiring a new write", async () => {
  const f = await fixture();
  try {
    f.createSession();
    f.store.create("memory_candidate", "session-candidate", { scope: { kind: "session", id: f.id }, status: "candidate" });
    f.store.create("memory_confirmation", "session-confirmation", { scope: { kind: "session", id: f.id }, status: "active" });
    const oldDirectory = join(sessionBase, legacyId(f.id));
    f.writeProjection(oldDirectory);
    f.writeProjection(join(sessionBase, f.id));
    const result = f.files.archiveSession(f.id);
    assert.equal(result.memory_count, 1);
    assert.equal(result.candidate_count, 1);
    assert.equal(result.confirmation_count, 1);
    assert.equal(existsSync(oldDirectory), false);
    assert.equal(existsSync(join(sessionBase, f.id)), false);
    assert.equal(f.store.count("memory_candidate"), 0);
    assert.equal(f.store.count("memory_confirmation"), 0);
    assert.equal(f.files.archiveSession(f.id).idempotent, true);
  } finally { f.cleanup(); }
});


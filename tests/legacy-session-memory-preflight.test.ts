function putScopeDatabase(path: string, scopes: unknown[]): void {
  const database = new DatabaseSync(path);
  try {
    database.exec("CREATE TABLE records(kind TEXT,id TEXT,version INTEGER,payload_json TEXT,created_at TEXT,updated_at TEXT);");
    const insert = database.prepare("INSERT INTO records VALUES(?,?,1,?,?,?)");
    scopes.forEach((scope, index) => insert.run("memory_ledger", `memory-${index}`, JSON.stringify({ scope }), "now", "now"));
  } finally { database.close(); }
}

test("legacy session Memory inventory pages read-only artifacts and resolves only unique Host mappings", async () => {
  const root = mkdtempSync(join(tmpdir(), "craft-legacy-session-preflight-"));
  const paths = craftPaths(join(root, "data")), legacy = join(root, "legacy-memory");
  mkdirSync(legacy);
  const store = await new CraftStore(paths).open();
  try {
    const readyId = "legacy-ready-session";
    const readyDirectory = join(legacy, createHash("sha256").update(readyId).digest("hex").slice(0, 32));
    mkdirSync(readyDirectory);
    putScopeDatabase(join(readyDirectory, "memory.db"), [{ kind: "session", id: readyId }]);
    mkdirSync(join(readyDirectory, "nested")); writeFileSync(join(readyDirectory, "nested", "note.txt"), "metadata scan fixture");
    store.bindSessionStorageHost(readyId, "codex");

    const unboundId = "legacy-unbound-session", unboundDirectory = join(legacy, unboundId);
    mkdirSync(unboundDirectory);
    writeFileSync(join(unboundDirectory, "memory.md"), `# Memory\n\n<!-- scope: session:${unboundId}; generated by Craft -->\n\nprivate fact\n`);

    const ambiguousId = "legacy-ambiguous-host", ambiguousDirectory = join(legacy, ambiguousId);
    mkdirSync(ambiguousDirectory);
    putScopeDatabase(join(ambiguousDirectory, "memory.db"), [{ kind: "session", id: ambiguousId }]);
    store.bindSessionStorageHost(ambiguousId, "codex");
    store.bindSessionStorageHost(ambiguousId, "claude");

    const oldBindingId = "legacy-binding-without-modern-fields", oldBindingDirectory = join(legacy, oldBindingId);
    mkdirSync(oldBindingDirectory);
    putScopeDatabase(join(oldBindingDirectory, "memory.db"), [`session:${oldBindingId}`]);
    store.database.prepare("INSERT INTO records(kind,id,version,payload_json,created_at,updated_at) VALUES(?,?,1,?,?,?)")
      .run("session_storage_identity", "legacy-binding-without-modern-fields", JSON.stringify({ host: "codex", session_id: oldBindingId }), "now", "now");
    mkdirSync(sessionStorageDirectory(paths, "codex", oldBindingId), { recursive: true });

    for (const [id, binding] of [
      ["bad-binding-digest", { host: "codex", session_id: "bad-binding-digest", session_digest: "wrong" }],
      ["bad-binding-scope", { host: "codex", session_id: "bad-binding-scope", scope_id: "foreign--scope" }],
      ["bad-binding-host", { host: "../codex", session_id: "bad-binding-host" }],
    ] as const) {
      const directory = join(legacy, id); mkdirSync(directory);
      putScopeDatabase(join(directory, "memory.db"), [{ kind: "session", id }]);
      store.database.prepare("INSERT INTO records(kind,id,version,payload_json,created_at,updated_at) VALUES(?,?,1,?,?,?)")
        .run("session_storage_identity", `binding-${id}`, JSON.stringify(binding), "now", "now");
    }

    const mixedDirectory = join(legacy, "legacy-mixed-scope");
    mkdirSync(mixedDirectory);
    putScopeDatabase(join(mixedDirectory, "memory.db"), [{ kind: "session", id: "one" }, { kind: "session", id: "two" }]);
    const mismatchDirectory = join(legacy, "legacy-mismatched-name");
    mkdirSync(mismatchDirectory);
    putScopeDatabase(join(mismatchDirectory, "memory.db"), [{ kind: "session", id: readyId }]);
    const jsonScopeId = "legacy-json-scope", jsonScopeDirectory = join(legacy, jsonScopeId);
    mkdirSync(jsonScopeDirectory);
    putScopeDatabase(join(jsonScopeDirectory, "memory.db"), [JSON.stringify({ kind: "session", id: jsonScopeId })]);
    store.bindSessionStorageHost(jsonScopeId, "codex");
    const emptyScopeDirectory = join(legacy, "empty-scope"); mkdirSync(emptyScopeDirectory);
    putScopeDatabase(join(emptyScopeDirectory, "memory.db"), [{ kind: "session", id: " " }, "{", ["not-a-scope"]]);
    const noRecordsDirectory = join(legacy, "no-records-table"); mkdirSync(noRecordsDirectory);
    const noRecordsDb = new DatabaseSync(join(noRecordsDirectory, "memory.db"));
    noRecordsDb.exec("CREATE TABLE other(value TEXT)"); noRecordsDb.close();
    writeFileSync(join(legacy, "unscoped.bin"), "x");

    const first = legacySessionMemoryPreflight(paths, { legacy_root: legacy, max_entries: 5 });
    assert.equal(first.root_status, "ready");
    assert.equal(first.examined, 5);
    assert.equal(first.has_more, true);
    const second = legacySessionMemoryPreflight(paths, { legacy_root: legacy, max_entries: 20, cursor: first.next_cursor! });
    const entries = [...first.entries, ...second.entries];
    assert.equal(second.has_more, false);
    const byStatus = Object.fromEntries(entries.map(item => [item.source_digest, item.status]));
    assert.equal(entries.find(item => item.host === "codex" && item.session_digest === `sha256:${createHash("sha256").update(readyId).digest("hex")}`)?.status, "legacy_ready");
    assert.equal(entries.find(item => item.source_digest === `sha256:${createHash("sha256").update(unboundId).digest("hex")}`)?.status, "unbound_host");
    assert(entries.some(item => item.status === "ambiguous_host"));
    assert(entries.some(item => item.status === "ambiguous_session"));
    assert(entries.some(item => item.status === "identity_mismatch"));
    assert(entries.some(item => item.status === "unscoped_entry"));
    assert(Object.keys(byStatus).length >= 10);
    assert.equal(entries.find(item => item.status === "legacy_ready" && !item.target_exists)?.target_exists, false);
    assert.equal(entries.find(item => item.host === "codex" && item.target_exists)?.status, "target_conflict");
    assert(entries.filter(item => item.status === "unidentified_session").length >= 2);
    assert(entries.filter(item => item.status === "unbound_host").length >= 3);
    assert(entries.some(item => item.status === "identity_mismatch"));
    assert.equal(lstatSync(join(readyDirectory, "memory.db")).isFile(), true);
    assert.throws(() => legacySessionMemoryPreflight(paths, { legacy_root: legacy, max_entries: 0 }), /max_entries/u);
    for (const cursor of ["!", Buffer.from("[]").toString("base64url"), Buffer.from("not-json").toString("base64url")]) {
      assert.throws(() => legacySessionMemoryPreflight(paths, { legacy_root: legacy, cursor }), /cursor is invalid/u);
    }
  } finally { store.close(); rmSync(root, { recursive: true, force: true }); }
});

test("legacy session Memory inventory fails closed on missing, linked, malformed and unavailable sources", async () => {
  const root = mkdtempSync(join(tmpdir(), "craft-legacy-session-preflight-errors-"));
  const paths = craftPaths(join(root, "data")), missing = join(root, "missing");
  const store = await new CraftStore(paths).open();
  try {
    assert.equal(legacySessionMemoryPreflight(paths, { legacy_root: missing }).root_status, "missing");
    const target = join(root, "target"), linked = join(root, "linked");
    mkdirSync(target); writeFileSync(join(target, "memory.md"), "# Memory\n");
    symlinkSync(target, linked);
    assert.equal(legacySessionMemoryPreflight(paths, { legacy_root: linked }).root_status, "unsafe");

    const legacy = join(root, "legacy"); mkdirSync(legacy);
    const linkedEntry = join(legacy, "linked-entry"); symlinkSync(target, linkedEntry);
    const brokenLink = join(legacy, "broken-link"); symlinkSync(join(root, "missing-target"), brokenLink);
    const loopingLink = join(legacy, "looping-link"); symlinkSync("looping-link", loopingLink);
    const nestedLink = join(legacy, "nested-link"); mkdirSync(nestedLink); symlinkSync(target, join(nestedLink, "linked"));
    const malformed = join(legacy, "malformed"); mkdirSync(malformed); writeFileSync(join(malformed, "memory.db"), "not sqlite");
    const id = "no-central-binding";
    const unidentified = join(legacy, id); mkdirSync(unidentified);
    writeFileSync(join(unidentified, "memory.md"), `# Memory\n\n<!-- scope: session:${id}; generated by Craft -->\n`);
    const inaccessibleId = "target-stat-error", inaccessibleDirectory = join(legacy, inaccessibleId);
    mkdirSync(inaccessibleDirectory);
    putScopeDatabase(join(inaccessibleDirectory, "memory.db"), [{ kind: "session", id: inaccessibleId }]);
    store.bindSessionStorageHost(inaccessibleId, "codex");
    const result = legacySessionMemoryPreflight(paths, { legacy_root: legacy });
    assert.equal(result.root_status, "ready");
    assert(result.entries.some(item => item.status === "unsafe_path"));
    assert(result.entries.some(item => item.status === "broken_symlink"));
    assert(result.entries.some(item => item.status === "unbound_host"));
    assert(result.entries.some(item => item.status === "source_unreadable"));
    const withoutCentral = craftPaths(join(root, "absent-data"));
    const noCentral = legacySessionMemoryPreflight(withoutCentral, { legacy_root: legacy });
    assert(noCentral.entries.some(item => item.status === "binding_unavailable"));

    const regularRoot = join(root, "regular-root"); writeFileSync(regularRoot, "x");
    assert.equal(legacySessionMemoryPreflight(paths, { legacy_root: regularRoot }).root_status, "unsafe");
    assert.throws(() => legacySessionMemoryPreflight(paths, { legacy_root: `${legacy}\0bad` }));

    const targetPath = sessionStorageDirectory(paths, "codex", inaccessibleId), originalLstat = fs.lstatSync;
    try {
      fs.lstatSync = ((path: string) => {
        if (path === targetPath) throw Object.assign(new Error("injected target stat failure"), { code: "EACCES" });
        return originalLstat(path);
      }) as unknown as typeof fs.lstatSync;
      syncBuiltinESMExports();
      assert(legacySessionMemoryPreflight(paths, { legacy_root: legacy }).entries.some(item => item.status === "unsafe_path"));
    } finally { fs.lstatSync = originalLstat; syncBuiltinESMExports(); }

    const deniedDirectory = join(legacy, "denied-directory"); mkdirSync(deniedDirectory);
    const originalReaddir = fs.readdirSync;
    try {
      fs.readdirSync = ((path: string) => {
        if (String(path) === deniedDirectory) throw Object.assign(new Error("injected directory read error"), { code: "EACCES" });
        return originalReaddir(path);
      }) as unknown as typeof fs.readdirSync;
      syncBuiltinESMExports();
      assert(legacySessionMemoryPreflight(paths, { legacy_root: legacy }).entries.some(item => item.status === "unsafe_path"));
    } finally { fs.readdirSync = originalReaddir; syncBuiltinESMExports(); }

    if (process.platform !== "win32") {
      const specialDirectory = join(legacy, "special-child"); mkdirSync(specialDirectory);
      const fifo = join(specialDirectory, "pipe"), created = spawnSync("mkfifo", [fifo]);
      assert.equal(created.status, 0, created.stderr.toString());
      assert(legacySessionMemoryPreflight(paths, { legacy_root: legacy }).entries.some(item => item.status === "unsafe_path"));
    }
  } finally { store.close(); rmSync(root, { recursive: true, force: true }); }
});

import { createHash } from "node:crypto";
import { closeSync, lstatSync, openSync, readSync, readdirSync, realpathSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { basename, join } from "node:path";
import { sessionStorageScopeId, sessionStorageDirectory, type CraftPaths } from "../common/craft-common-store-local/src/paths.ts";

type Status = "legacy_ready" | "unbound_host" | "ambiguous_host" | "ambiguous_session" | "unidentified_session"
  | "identity_mismatch" | "unscoped_entry" | "unsafe_path" | "broken_symlink" | "binding_unavailable" | "source_unreadable" | "target_conflict";

export interface LegacySessionMemoryEntry {
  source_digest: string;
  status: Status;
  session_digest: string | null;
  host: string | null;
  target_directory: string | null;
  target_exists: boolean;
  file_count: number;
  bytes: number;
}

function decodeCursor(cursor?: string): string {
  if (cursor === undefined) return "";
  if (!/^[A-Za-z0-9_-]{1,512}$/u.test(cursor)) throw new Error("Legacy session preflight cursor is invalid");
  try {
    const value: unknown = JSON.parse(Buffer.from(cursor, "base64url").toString("utf8"));
    if (typeof value === "string" && value.length <= 255) return value;
  } catch { /* reject malformed cursor below */ }
  throw new Error("Legacy session preflight cursor is invalid");
}

function encodeCursor(name: string): string { return Buffer.from(JSON.stringify(name)).toString("base64url"); }

function regularTreeStats(root: string): { files: string[]; bytes: number; safe: boolean } {
  const files: string[] = [];
  let bytes = 0;
  const pending = [root];
  while (pending.length) {
    const directory = pending.pop()!;
    for (const name of readdirSync(directory)) {
      const path = join(directory, name), stat = lstatSync(path);
      if (stat.isSymbolicLink()) return { files, bytes, safe: false };
      if (stat.isDirectory()) pending.push(path);
      else if (stat.isFile()) { files.push(path); bytes += stat.size; }
      else return { files, bytes, safe: false };
    }
  }
  return { files, bytes, safe: true };
}

function sessionIdFromScope(scope: unknown): string | null {
  if (typeof scope === "string") {
    if (scope.startsWith("session:") && scope.length > "session:".length) return scope.slice("session:".length);
    try { scope = JSON.parse(scope); } catch { return null; }
  }
  if (!scope || typeof scope !== "object" || Array.isArray(scope)) return null;
  const value = scope as Record<string, unknown>;
  return value.kind === "session" && typeof value.id === "string" && value.id.trim() ? value.id : null;
}

function scopeIds(files: string[]): Set<string> {
  const ids = new Set<string>();
  for (const file of files) {
    if (basename(file) === "memory.db") {
      const database = new DatabaseSync(file, { readOnly: true });
      try {
        const exists = database.prepare("SELECT 1 FROM sqlite_master WHERE type='table' AND name='records'").get();
        if (!exists) continue;
        const scopes = database.prepare(`SELECT DISTINCT json_extract(payload_json,'$.scope') scope FROM records
          WHERE kind LIKE 'memory_%' AND json_type(payload_json,'$.scope') IS NOT NULL`).all() as Array<{ scope: unknown }>;
        for (const row of scopes) { const id = sessionIdFromScope(row.scope); if (id) ids.add(id); }
      } finally { database.close(); }
    } else if (basename(file) === "memory.md") {
      const fd = openSync(file, "r"), buffer = Buffer.alloc(65_664);
      try {
        const length = readSync(fd, buffer, 0, buffer.length, 0);
        const header = buffer.toString("utf8", 0, length);
        const match = /^# Memory\r?\n\r?\n<!-- scope: session:([^;\r\n]+); generated by Craft -->/u.exec(header);
        if (match?.[1]) ids.add(match[1]);
      } finally { closeSync(fd); }
    }
  }
  return ids;
}

function hostBindings(database: DatabaseSync, sessionId: string): string[] {
  const rows = database.prepare(`SELECT payload_json FROM records AS binding WHERE kind='session_storage_identity'
    AND json_extract(payload_json,'$.session_id')=? AND version=(SELECT MAX(version) FROM records AS latest
      WHERE latest.kind=binding.kind AND latest.id=binding.id)`).all(sessionId) as Array<{ payload_json: string }>;
  const hosts = new Set<string>();
  const rawDigest = createHash("sha256").update(sessionId).digest("hex");
  for (const row of rows) {
    const item = JSON.parse(row.payload_json) as Record<string, unknown>;
    const host = item.host;
    if (typeof host !== "string" || !/^[a-z][a-z0-9_-]{0,31}$/u.test(host)) continue;
    if (item.session_digest !== undefined && item.session_digest !== rawDigest) continue;
    const scopeId = sessionStorageScopeId(host, sessionId);
    if (item.scope_id !== undefined && item.scope_id !== scopeId) continue;
    hosts.add(host);
  }
  return [...hosts].sort();
}

function entryFor(paths: CraftPaths, source: string, sourceName: string, database: DatabaseSync | null): LegacySessionMemoryEntry {
  const sourceDigest = createHash("sha256").update(sourceName).digest("hex");
  const base = { source_digest: `sha256:${sourceDigest}`, session_digest: null, host: null, target_directory: null,
    target_exists: false, file_count: 0, bytes: 0 };
  const stat = lstatSync(source);
  if (stat.isSymbolicLink()) {
    try { realpathSync(source); return { ...base, status: "unsafe_path" }; }
    catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return { ...base, status: "broken_symlink" };
      return { ...base, status: "unsafe_path" };
    }
  }
  if (!stat.isDirectory()) return { ...base, status: "unscoped_entry", file_count: 1, bytes: stat.size };
  let tree: ReturnType<typeof regularTreeStats>;
  try { tree = regularTreeStats(source); } catch { return { ...base, status: "unsafe_path" }; }
  const measured = { ...base, file_count: tree.files.length, bytes: tree.bytes };
  if (!tree.safe) return { ...measured, status: "unsafe_path" };
  let ids: Set<string>;
  try { ids = scopeIds(tree.files); } catch { return { ...measured, status: "source_unreadable" }; }
  if (ids.size === 0) return { ...measured, status: "unidentified_session" };
  if (ids.size > 1) return { ...measured, status: "ambiguous_session" };
  const sessionId = [...ids][0]!;
  const sessionDigest = createHash("sha256").update(sessionId).digest("hex");
  const expectedDirectory = sessionDigest.slice(0, 32);
  if (sourceName !== sessionId && sourceName !== expectedDirectory) return { ...measured, status: "identity_mismatch", session_digest: `sha256:${sessionDigest}` };
  if (!database) return { ...measured, status: "binding_unavailable", session_digest: `sha256:${sessionDigest}` };
  const hosts = hostBindings(database, sessionId);
  if (hosts.length === 0) return { ...measured, status: "unbound_host", session_digest: `sha256:${sessionDigest}` };
  if (hosts.length > 1) return { ...measured, status: "ambiguous_host", session_digest: `sha256:${sessionDigest}` };
  const host = hosts[0]!;
  const targetDirectory = sessionStorageDirectory(paths, host, sessionId);
  let targetExists = false;
  try { lstatSync(targetDirectory); targetExists = true; }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") return { ...measured, status: "unsafe_path", session_digest: `sha256:${sessionDigest}`, host, target_directory: targetDirectory }; }
  return { ...measured, status: targetExists ? "target_conflict" : "legacy_ready", session_digest: `sha256:${sessionDigest}`, host,
    target_directory: targetDirectory, target_exists: targetExists };
}

/** Read-only paged inventory of detached `/tmp/.craft_data/memory` artifacts. */
export function legacySessionMemoryPreflight(paths: CraftPaths, args: {
  legacy_root: string; max_entries?: number; cursor?: string;
}): { root_status: "missing" | "ready" | "unsafe"; entries: LegacySessionMemoryEntry[]; examined: number; has_more: boolean; next_cursor: string | null } {
  const limit = args.max_entries ?? 100;
  if (!Number.isSafeInteger(limit) || limit < 1 || limit > 500) throw new Error("max_entries must be between 1 and 500");
  const after = decodeCursor(args.cursor);
  const root = args.legacy_root;
  let rootStat;
  try { rootStat = lstatSync(root); }
  catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return { root_status: "missing", entries: [], examined: 0, has_more: false, next_cursor: null };
    throw error;
  }
  if (rootStat.isSymbolicLink() || !rootStat.isDirectory()) return { root_status: "unsafe", entries: [], examined: 0, has_more: false, next_cursor: null };
  let database: DatabaseSync | null = null;
  try {
    const centralStat = lstatSync(paths.databaseFile);
    if (!centralStat.isSymbolicLink() && centralStat.isFile()) database = new DatabaseSync(paths.databaseFile, { readOnly: true });
  } catch { database = null; }
  try {
    const names = readdirSync(root).filter(name => name > after).sort().slice(0, limit + 1);
    const page = names.slice(0, limit), entries = page.map(name => entryFor(paths, join(root, name), name, database));
    const hasMore = names.length > limit;
    return { root_status: "ready", entries, examined: entries.length, has_more: hasMore,
      next_cursor: hasMore && page.length ? encodeCursor(page.at(-1)!) : null };
  } finally { database?.close(); }
}
